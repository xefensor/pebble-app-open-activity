#!/usr/bin/env python3
"""Regenerate fixed setup-header ink bounds from the app's built SDK font.

Build the app first, then run this script. Normal builds use the committed
table and do not depend on this generator or the sibling repositories.
"""
from pathlib import Path
import argparse
import hashlib
import json
import struct

ROOT = Path(__file__).resolve().parents[1]


def glyph_ink(data):
    version, height, count, wildcard, buckets, cp_bytes, header, features = struct.unpack_from('<BBHHBBBB', data)
    assert version == 3 and cp_bytes in (2, 4) and features & ~1 == 0
    offset_bytes = 2 if features & 1 else 4
    table = header + buckets * 4
    base = table + count * (cp_bytes + offset_bytes)
    result = {}
    for bucket in range(buckets):
        _, number, position = struct.unpack_from('<BBH', data, header + bucket * 4)
        for i in range(number):
            at = table + position + i * (cp_bytes + offset_bytes)
            code = int.from_bytes(data[at:at + cp_bytes], 'little')
            offset = int.from_bytes(data[at + cp_bytes:at + cp_bytes + offset_bytes], 'little')
            width, rows, left, top, advance = struct.unpack_from('<BBbbb', data, base + offset)
            bitmap = data[base + offset + 5:base + offset + 5 + (width * rows + 7) // 8]
            result[code] = (top, top + rows - 1) if any(bitmap) else (127, 0)
    return result


def generate(pack):
    package = json.loads((ROOT / 'package.json').read_text())
    packed = pack.read_bytes()
    index = next(i for i, item in enumerate(package['pebble']['resources']['media']) if item['name'] == 'FONT_BODY_26')
    _, offset, size, _ = struct.unpack_from('<4I', packed, 12 + index * 16)
    pfo = packed[4108 + offset:4108 + offset + size]
    metrics = glyph_ink(pfo)
    fallback = json.loads((ROOT / 'tests/fixtures/header-fallback-ink.json').read_text())
    codes = list(range(32, 127)) + [0x2026, 0x25af]
    assert all(code in metrics for code in codes)
    stock = {row[0]: tuple(row[1:]) for row in fallback['glyphs']}
    rows = [
        '// Generated by scripts/generate-header-ink.py; do not edit.',
        '// Roboto Condensed: SIL Open Font License 1.1; resources/fonts/OFL-RobotoCondensed.txt.',
        '// Source TTF SHA256: ' + hashlib.sha256((ROOT / 'resources/fonts/RobotoCondensed-Bold.ttf').read_bytes()).hexdigest(),
        '// Packaged Roboto26 PFO SHA256: ' + hashlib.sha256(pfo).hexdigest(),
        '// Gothic28 fallback: public native SDK4.33.1 drawing; tests/fixtures/header-fallback-ink.json.',
        '#pragma once', '#include <stdint.h>',
        'typedef struct { int8_t top, bottom; } OaGlyphInk;',
        'static const OaGlyphInk oa_header_glyphs[2][97] = {',
    ]
    for font in (metrics, stock):
        rows.append('  {')
        for start in range(0, len(codes), 12):
            rows.append('    ' + ','.join('{%d,%d}' % font[code] for code in codes[start:start + 12]) + ',')
        rows.append('  },')
    rows += ['};', '']
    return '\n'.join(rows)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pack', type=Path, default=ROOT / 'build/emery/app_resources.pbpack')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'src/c/generated_header_ink.h'
    expected = generate(args.pack)
    if args.check:
        assert output.read_text() == expected, 'Header ink table differs from the packaged font'
    else:
        output.write_text(expected)
    print('Header ink table matches packaged Roboto26 and recorded SDK fallback')
